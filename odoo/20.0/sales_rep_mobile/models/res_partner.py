from odoo import api, fields, models


class ResPartner(models.Model):
    _inherit = 'res.partner'

    sales_rep_id = fields.Many2one('sales.rep', string='Van Sales Rep', index=True,
                                   help='Rep responsible for visiting this customer.')
    is_sales_rep = fields.Boolean(string='Is a Sales Rep', copy=False,
                                  help='This partner is a van rep (invoiced for loaded goods).')
    mobile_uuid = fields.Char(copy=False, index=True, readonly=True,
                              help='Identifier generated by the mobile app when the rep '
                                   'created this customer offline.')
    rep_customer_due = fields.Monetary(
        string='Due to Rep', compute='_compute_rep_customer_due', currency_field='currency_id',
        help='Unpaid van sales of this customer minus returns and collections.')

    _mobile_uuid_uniq = models.UniqueIndex('(mobile_uuid) WHERE mobile_uuid IS NOT NULL')

    @api.depends_context('company')
    def _compute_rep_customer_due(self):
        Sale = self.env['sales.rep.van.sale'].sudo()
        Coll = self.env['sales.rep.collection'].sudo()
        sales = dict(Sale._read_group(
            [('partner_id', 'in', self.ids), ('state', '=', 'done')],
            ['partner_id'], ['signed_due:sum']))
        colls = dict(Coll._read_group(
            [('partner_id', 'in', self.ids), ('state', '=', 'done')],
            ['partner_id'], ['amount:sum']))
        for partner in self:
            partner.rep_customer_due = sales.get(partner, 0.0) - colls.get(partner, 0.0)
